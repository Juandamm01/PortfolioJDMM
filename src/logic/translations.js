export const defaultLanguage = 'es';

export function getCurrentLanguage() {
  if (typeof document === 'undefined') return defaultLanguage;

  let stored = defaultLanguage;

  if (typeof window !== 'undefined' && window.localStorage) {
    const savedLang = window.localStorage.getItem('portfolio-lang');
    if (savedLang === 'en' || savedLang === 'es') {
      stored = savedLang;
    }
  }

  const current = stored || document.documentElement?.lang || document.body?.dataset?.lang || defaultLanguage;
  return current === 'en' ? 'en' : 'es';
}

export function getLocalizedText(key, lang = getCurrentLanguage()) {
  return (translations[lang] && translations[lang][key]) || (translations.es[key] ?? '');
}

export function setLanguage(lang) {
  const normalized = lang === 'en' ? 'en' : 'es';

  if (typeof document !== 'undefined') {
    document.documentElement.lang = normalized;
    document.body?.setAttribute('data-lang', normalized);
    if (window.localStorage) {
      window.localStorage.setItem('portfolio-lang', normalized);
    }
  }

  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('portfolio:lang-change', { detail: { lang: normalized } }));
  }

  return normalized;
}

export function applyTranslations(lang = getCurrentLanguage()) {
  if (typeof document === 'undefined') return lang;

  const active = translations[lang] || translations.es;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.getAttribute('data-i18n');
    const value = active[key];
    if (value) {
      element.innerHTML = value;
    }
  });

  const cvBtn = document.getElementById('download-cv-btn');
  if (cvBtn) {
    const filename = lang === 'es' ? 'CV_Español.pdf' : 'CV_English.pdf';
    cvBtn.href = `/pdf/${filename}`;
    cvBtn.setAttribute('download', filename);
  }

  const logoLink = document.querySelector('.logo');
  if (logoLink) {
    logoLink.setAttribute('aria-label', lang === 'es' ? 'Inicio — Juan David Martínez' : 'Home — Juan David Martínez');
  }

  const langToggle = document.getElementById('lang-toggle');
  if (langToggle) {
    langToggle.textContent = lang === 'es' ? 'EN' : 'ES';
  }

  const mobileToggle = document.getElementById('lang-toggle-mobile');
  if (mobileToggle) {
    mobileToggle.textContent = lang === 'es' ? 'EN' : 'ES';
  }

  return lang;
}
